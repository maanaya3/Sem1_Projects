def gym_battle():
    global pokemon_level
    global pokemon_name
    choice = random.randint(1,2)
    if choice == 1:
        print("Your pokemon fights with ferocity you have never seen! " + pokemon_name + " has leveled up by 2!")
    else:
        print("Despite your pokemon's best attempts, they lost the gym battle and " + pokemon_name +  " has increased by 0")
